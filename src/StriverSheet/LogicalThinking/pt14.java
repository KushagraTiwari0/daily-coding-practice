package StriverSheet.LogicalThinking;

public class pt14 {
    public static void main(String[] args) {
        int n=5;
        for(int i=0;i<n;i++)
        {
            for(int j=0;j<=0+i;j++)
            {
                System.out.print((char)('A'+j));
            }
            System.out.println();
        }
    }
    
}
